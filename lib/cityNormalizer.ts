/**
 * Нормализует название города, приводя его к единому виду
 * @param cityName - Название города в любом варианте написания
 * @returns Нормализованное название города или исходное, если не найдено
 */
export function normalizeCityName(cityName: string): string {
  if (!cityName || typeof cityName !== "string") {
    return cityName;
  }

  // Убираем лишние пробелы и приводим к правильному регистру
  const trimmed = cityName.trim();
  
  // Проверяем точное совпадение (уже нормализованное)
  const lower = trimmed.toLowerCase();
  if (cityNormalizations[lower]) {
    return cityNormalizations[lower];
  }

  // Проверяем, является ли это известным городом (уже в правильном формате)
  if (knownCities.has(trimmed)) {
    return trimmed;
  }

  // Если не найдено в словаре, возвращаем с правильным регистром
  // Первая буква заглавная, остальные строчные
  return trimmed.charAt(0).toUpperCase() + trimmed.slice(1).toLowerCase();
}

/**
 * Проверяет, является ли строка названием города
 * @param location - Строка для проверки
 * @returns true, если это похоже на город
 */
export function isCityName(location: string): boolean {
  if (!location || typeof location !== "string") {
    return false;
  }

  const normalized = normalizeCityName(location);
  
  // Проверяем, есть ли в списке известных городов
  if (knownCities.has(normalized)) {
    return true;
  }

  // Проверяем, не является ли это координатами (содержит цифры и запятые/точки)
  const hasCoordinates = /^-?\d+\.?\d*,\s*-?\d+\.?\d*$/.test(location.trim());
  if (hasCoordinates) {
    return false;
  }

  // Проверяем, не является ли это адресом (содержит слова типа "улица", "дом" и т.д.)
  const addressKeywords = ["улица", "ул.", "дом", "д.", "проспект", "пр.", "бульвар", "б-р", "переулок", "пер.", "street", "st", "avenue", "ave"];
  const lowerLocation = location.toLowerCase();
  if (addressKeywords.some(keyword => lowerLocation.includes(keyword))) {
    return false;
  }

  // Если строка слишком длинная (больше 50 символов), вероятно это адрес
  if (location.length > 50) {
    return false;
  }

  // Если содержит только цифры и знаки препинания, это не город
  if (/^[\d\s\.,\-/]+$/.test(location)) {
    return false;
  }

  // Если выглядит как дробь или математическое выражение (например, "135/7", "50.5", "100-200")
  if (/^\d+[\s]*[\/\-\.][\s]*\d+$/.test(location.trim())) {
    return false;
  }

  // Если начинается с цифры и содержит только цифры, слэши и дефисы, это не город
  if (/^\d+[\s\-\/]*\d*$/.test(location.trim())) {
    return false;
  }

  // Если содержит меньше 2 букв, это не город
  const letterCount = (location.match(/[а-яА-ЯёЁa-zA-Z]/g) || []).length;
  if (letterCount < 2) {
    return false;
  }

  // Исключаем названия стран
  const countryNames = ["казахстан", "kazakhstan", "россия", "russia", "узбекистан", "uzbekistan"];
  if (countryNames.includes(lowerLocation)) {
    return false;
  }

  // Исключаем названия областей/регионов (обычно заканчиваются на "область", "region", "район")
  const regionKeywords = ["область", "region", "район", "district", "ауыл", "аудан"];
  if (regionKeywords.some(keyword => lowerLocation.includes(keyword))) {
    return false;
  }

  return true;
}

